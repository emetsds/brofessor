def text(language: str, message: str, **values) -> str:
    template = RUSSIAN[message] if language == InterfaceLanguage.RU else message
    return template.format(**values)


def load_language(browser_locale: str | None = None) -> str:
    language = preferences.read().get("ui_language")
    if isinstance(language, str) and language in LANGUAGE_NAMES:
        return language
    return (
        InterfaceLanguage.RU
        if not browser_locale or browser_locale.lower().startswith(InterfaceLanguage.RU)
        else InterfaceLanguage.EN
    )
